import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const snapshotPath = resolve(root, 'skillnet-api/src/personalization/didact_snapshot.json')
const outputPath = resolve(root, 'skillnet-web/src/lib/didact/generated-registry.ts')

const snapshot = JSON.parse(await readFile(snapshotPath, 'utf8'))
const manifests = new Map(snapshot.manifests.map((manifest) => [manifest.id, manifest]))

const sourceModuleOverrides = new Map([
  ['progress-indicators', 'progress-indicator'],
])

const entries = snapshot.available_types.map((type) => {
  const manifest = manifests.get(type.manifest_id)
  if (!manifest) throw new Error(`${type.id} references missing manifest ${type.manifest_id}`)
  const sourceModule = sourceModuleOverrides.get(type.registry_item) ?? type.registry_item
  return {
    componentId: type.id,
    manifestId: type.manifest_id,
    exportName: type.export_name,
    registryItem: type.registry_item,
    maturity: manifest.lifecycle.maturity,
    didactVersion: manifest.version.component,
    lazyModule: {
      strategy: 'vendor-export',
      exportName: type.export_name,
      registryItem: type.registry_item,
      sourceModule,
    },
    adapter: {
      rendererAvailable: true,
      rendererSymbol: type.export_name,
    },
  }
})

if (entries.length !== 34 || new Set(entries.map((entry) => entry.componentId)).size !== 34) {
  throw new Error(`Expected 34 unique Didact types, got ${entries.length}`)
}

const source = `/* eslint-disable */
// Generated by scripts/generate-didact-registry.mjs from the pinned neutral snapshot.
// Do not edit by hand. This is installed availability, never an OpenUI shortlist.
import type { DidactRegistryEntry } from './registry-types'

export const DIDACT_REGISTRY_SOURCE = ${JSON.stringify({
  repository: snapshot.source.repository,
  commit: snapshot.source.commit,
  contentSha256: snapshot.content_sha256,
}, null, 2)} as const

export const DIDACT_COMPONENT_REGISTRY = ${JSON.stringify(entries, null, 2)} as const satisfies readonly DidactRegistryEntry[]

export const DIDACT_COMPONENT_BY_ID: ReadonlyMap<string, DidactRegistryEntry> = new Map(
  DIDACT_COMPONENT_REGISTRY.map((entry) => [entry.componentId, entry]),
)
`

await writeFile(outputPath, source, 'utf8')

const loaderOutputPath = resolve(root, 'skillnet-web/src/lib/didact/generated-loaders.ts')
const registryItems = [...new Set(entries.map((entry) => entry.registryItem))]

const moduleLoaders = registryItems.map((registryItem) => {
  const sourceModule = sourceModuleOverrides.get(registryItem) ?? registryItem
  const importPath = `../../../vendor/didact/source/packages/core/src/components/${sourceModule}`
  return `  ${JSON.stringify(registryItem)}: () => import(${JSON.stringify(importPath)}),`
}).join('\n')

const componentLoaders = entries.map((entry) => `  ${JSON.stringify(entry.componentId)}: {
    componentId: ${JSON.stringify(entry.componentId)},
    exportName: ${JSON.stringify(entry.exportName)},
    registryItem: ${JSON.stringify(entry.registryItem)},
    loadModule: moduleLoaders[${JSON.stringify(entry.registryItem)}],
  },`).join('\n')

const loaderSource = `/* eslint-disable */
// Generated by scripts/generate-didact-registry.mjs. Dynamic imports exist only for
// host-ready adapters; unavailable entries fail explicitly without importing raw vendor code.
import {
  type DidactComponentLoaderEntry,
  type DidactModuleLoader,
} from './loader-types'

const moduleLoaders: Readonly<Record<string, DidactModuleLoader>> = {
${moduleLoaders}
}

export const DIDACT_COMPONENT_LOADERS = {
${componentLoaders}
} as const satisfies Readonly<Record<string, DidactComponentLoaderEntry>>

export async function loadDidactExport(componentId: string): Promise<unknown> {
  if (!(componentId in DIDACT_COMPONENT_LOADERS)) {
    throw new Error(\`Unknown Didact component \${componentId}\`)
  }
  const knownId = componentId as keyof typeof DIDACT_COMPONENT_LOADERS
  const entry = DIDACT_COMPONENT_LOADERS[knownId]
  const module = await entry.loadModule()
  const component = module[entry.exportName]
  if (component === undefined) {
    throw new Error(\`Didact module \${entry.registryItem} does not export \${entry.exportName}\`)
  }
  return component
}
`

await writeFile(loaderOutputPath, loaderSource, 'utf8')
console.log(`Generated ${entries.length} Didact registry entries and loaders`)
