"""The ``openui`` dialect — the server-side gate on generated programs (§5.4).

A **subset** of OpenUI Lang, parsed in Python. Line-oriented, one declaration per
*logical* line, **positional** arguments in the order of the kit table, children as
arrays:

    root = Stack([intro, steps, quiz], "md")
    intro = TextContent("Las devoluciones se aceptan durante 30 dias.", "lead")

A child may be written as a reference (above) or **inline** (below); both are the same
program once parsed, and :func:`_expand` flattens the inline form into the flat
``UISpec`` list with a synthetic id::

    root = Stack([TextContent("Las devoluciones se aceptan durante 30 dias.", "lead")], "md")
    # parses to the two components above, the inline one named `root_1`

Inline nesting was rejected until 2026-07-27 and that was **our** bug, not the model's:
the prompt this repository serves is generated by ``library.prompt()`` and says, in the
signature block, *"Sub-components can be inline or referenced; prefer references for
better streaming"*. Measured against ``qwen2.5:7b-instruct``, teaching a construction and
then refusing it cost a whole repair loop, because the parse error also misdiagnosed the
cause (see :meth:`_Scanner.missing_separator` and the note on error messages). ``serialize``
still writes the **referenced** form only — that is the canonical text, it is what their
prompt recommends for streaming, and it is what gives every block a real statement id in
the browser (an inline node parses with ``statementId: null`` there, which
``node_render_views`` cannot key on).

Since the adoption of the real dependency (2026-07-26, ``docs/design/openui-adoption.md``)
this module has **one** job and no longer has two:

* It **no longer teaches the dialect.** ``library.prompt()`` does, from the frontend kit,
  through the build-step artefacts that ``src/render/prompt.py`` reads. There is exactly
  one place where the catalogue is declared, and it is not here.
* It **still validates**, and it is the last gate before anything is persisted or served.
  The frozen grammar below has no production for ``$state``, ``{objects}``, ``@builtins``,
  ternaries, arithmetic, ``Query()`` or ``Mutation()``, so reactivity is *inexpressible*
  rather than blacklisted — which is why this parser was kept when the browser got its
  own. Their parser accepts a stray ``Mutation("delete_all_users", {...})`` with
  ``meta.errors == []``; this one cannot represent it. ``src/render/gate.py`` is the cheap
  door in front, ``serialize`` produces the canonical text the browser is allowed to see.

The standard is still wider than this subset: it accepts literal newlines inside strings,
booleans, ``null``, objects, arithmetic, ``//`` comments and markdown fences. It does
**not** require one declaration per physical line, and neither does this parser any more:
``src/render/lines.py`` joins the physical lines of a declaration the way
``lang-core``'s own statement splitter does (a newline inside an open bracket is not a
separator), and that module carries the measurement that forced the change. What is still
ours and not the standard's is the narrower half of escape rule 3: **a text value closes
its quote on the line that opened it**, which is what keeps ``parse_partial`` cheap.

Every error message this file raises is part of the contract with the LLM, not prose for
a human: the repair loop feeds them back verbatim (``build_repair_prompt``), so a message
that **guesses** the cause makes the model fix code that was never broken and the loop
stops converging. The rule here is therefore: name only what was actually observed, and
say what to write instead.

The frozen grammar, which this file *is* the implementation of. It used to be exported as
``GRAMMAR`` because it was pasted into the prompt; the prompt now comes from
``library.prompt()``, so it lives here as the specification of the gate and nothing reads
it as data::

    program    = { line } ;
    line       = ident "=" call line_break ;
    ident      = letter { letter | "0".."9" | "_" } ;   (* folded to ASCII, see below *)
    call       = comp_name "(" [ arg { "," arg } ] ")" ;
    comp_name  = "Stack" | "TextContent" | "Card" | "Callout" | "StepSequence"
               | "Table" | "CodeBlock" | "Chart" | "QuizItem" ;
    arg        = string | number | array | ident | call ;
    array      = "[" [ arg { "," arg } ] "]" ;
    string     = '"' { char | escape } '"' ;
    escape     = "\\" ( '"' | "\\" | "n" ) ;
    char       = <cualquier caracter excepto '"', '\\' y newline> ;
    number     = [ "-" ] digit { digit } [ "." digit { digit } ] ;

``line_break`` is a newline at bracket depth zero, not any newline: see
``src/render/lines.py``.

``letter`` is any Unicode letter, and the id is then **folded to ASCII** by
:func:`fold_identifier`, so ``conclusión`` is accepted and becomes ``conclusion``. This
is the one place where this parser is deliberately *wider* than ``lang-core``, and the
reason is that ``lang-core`` is narrower than it looks: its tokenizer takes identifiers
from ``[A-Za-z_][A-Za-z0-9_]*`` only, and the character it cannot classify it **silently
skips** (``dist/index.mjs``, the trailing ``i++`` of ``tokenize``). ``conclusión`` in the
browser is therefore not an error, it is two identifiers and a dropped statement — the
worst possible outcome for a validator whose job is to decide what may be served. So the
id cannot travel as written; but it also does not have to be refused, because it is
unambiguous. Folding it and serializing the folded form gives the browser the pure-ASCII
text its tokenizer needs, deterministically, and costs nothing: block ids are statement
keys and are never shown to the learner.

Measured, this was the single most expensive defect in the corpus: ``groq/llama-3.1-8b-instant``
failed ``atencion-reclamaciones`` **3 passes out of 3** on ``conclusión``
(``bench_out/failures/quality-20260727-030727``), both attempts each time, because the
product is Spanish and a Spanish-speaking model names its variables in Spanish. Note that
this is *not* the 79ede73 case — our grammar was not a strict subset here, both were ASCII
— which is why the fix is a normalisation and not a widening.

Two constraints the EBNF cannot state:

* A ``call`` as an ``arg`` is only meaningful where the kit declares a ``ref[]`` prop
  (``Stack.children``, ``Card.children``). Anywhere else it is a typed error, named as
  such rather than reported as a stray parenthesis.
* Nesting is capped at :data:`MAX_NESTING_DEPTH` levels per line, so a recursive or
  pathological program cannot pick the CPython recursion limit as its denial of service.

Two things the dialect does **not** carry, and how they are recovered:

* ``root`` — the id no other component lists among its children. Ties fall back to a
  component literally named ``root``, then to the first line.
* ``format`` — inferred from the component mix by :func:`infer_format`, unless the
  caller passes ``ui_format=`` (which is what the runtime does, since
  ``decide_formato`` already decided it). The inference and ``serialize`` agree, so
  ``parse(serialize(spec)) == spec`` holds without a header line, which the frozen
  grammar has no room for.
"""

