#: Where ``PronunciationExercise`` and ``AudioExplanation`` sit relative to the
#: JSON-derived block: the §5.3 table order interleaves the artefact's components with
#: the backend-only ones, so the known names are assembled name-by-name in this fixed
#: order. A component the artefact advertises that is NOT in this tuple (i.e. added on
#: the frontend after this tuple was last touched) is not dropped: :func:`_build_ui_kit`
#: appends it at the end, in the artefact's own order, with the ``ComponentSpec``
#: defaults (``is_container=False``, no function claim) — the same defaults every
#: component below with no ``_BACKEND_METADATA`` entry already gets. That default is
#: correct for the overwhelming majority of new components (leaf content blocks); a
#: genuinely new *container* or one that should compete for a ``ContentFunction`` still
#: needs a `_BACKEND_METADATA` entry added by hand, but nothing about *discovering* the
#: component requires touching this module first.
_CATALOGUE_ORDER: tuple[str, ...] = (
    "Stack", "TextContent", "Card", "Callout", "StepSequence", "Table", "CodeBlock",
    "Chart", "QuizItem", "BeforeAfter", "Markdown", "DragOrder", "AudioExplanation",
    "PodcastPlayer", "InfographicImage", "SourceImage", "PronunciationExercise", "Flashcard",
    "HintReveal", "DidactGlossary", "DidactTimeline", "DidactWorkedExample",
    "LearningExperience", "DidactActivity",
)

_HERE = Path(__file__).parent
_CATALOG_ARTIFACT_PATH = _HERE / "openui_catalog.json"

#: How to fix every error this module raises while loading the artefact.
_REGENERATE_HINT = (
    "regenerate the artefacts: cd apps/skillnet-web && "
    "node scripts/generate-openui-prompt.mjs"
)


def _load_catalog_artifact() -> dict[str, object]:
    try:
        raw = _CATALOG_ARTIFACT_PATH.read_text(encoding="utf-8")
    except OSError as exc:
        raise RuntimeError(
            f"missing render artefact {_CATALOG_ARTIFACT_PATH.name}: {_REGENERATE_HINT}"
        ) from exc
    try:
        return json.loads(raw)
    except json.JSONDecodeError as exc:
        raise RuntimeError(
            f"{_CATALOG_ARTIFACT_PATH.name} is not valid JSON: {_REGENERATE_HINT}"
        ) from exc


def _prop_from_artifact(raw: dict[str, object]) -> PropSpec:
    return PropSpec(
        name=str(raw["name"]),
        kind=PropKind(raw["kind"]),
        description="",
        choices=tuple(str(choice) for choice in (raw.get("choices") or ())),  # type: ignore[union-attr]
    )


def _component_from_artifact(raw: dict[str, object]) -> ComponentSpec:
    name = str(raw["name"])
    metadata = _BACKEND_METADATA.get(name, {})
    props = raw["props"]
    assert isinstance(props, list)
    return ComponentSpec(
        name=name,
        purpose=str(raw.get("description") or ""),
        props=tuple(_prop_from_artifact(prop) for prop in props),
        is_container=bool(metadata.get("is_container", False)),
        functions=tuple(metadata.get("functions", ())),  # type: ignore[arg-type]
    )


def _build_ui_kit() -> UIKit:
    """Assemble ``UI_KIT`` from ``openui_catalog.json`` plus the backend-only metadata.

    The two sources are keyed by component name and merged in :data:`_CATALOGUE_ORDER`
    (the fixed §5.3 table order), so a component's position among ties in
    :meth:`UIKit.candidates_for` cannot shift just because the artefact happened to list
    it differently.
    """
    artifact = _load_catalog_artifact()
    from_artifact = {
        str(component["name"]): _component_from_artifact(component)  # type: ignore[arg-type]
        for component in artifact["prompt_components"]  # type: ignore[union-attr]
    }
    backend_only = {component.name: component for component in _BACKEND_ONLY_COMPONENTS}

    missing = [name for name in _CATALOGUE_ORDER if name not in from_artifact and name not in backend_only]
    if missing:
        raise RuntimeError(
            f"catalogue order names {missing} that neither the artefact nor "
            f"_BACKEND_ONLY_COMPONENTS declares: {_REGENERATE_HINT}"
        )

    # Names the artefact advertises but `_CATALOGUE_ORDER` predates: appended at the end,
    # in the artefact's own order, so a component added on the frontend surfaces here
    # automatically instead of being silently dropped (see the comment on the tuple).
    discovered = [name for name in from_artifact if name not in _CATALOGUE_ORDER]

    order = (*_CATALOGUE_ORDER, *discovered)
    return UIKit(
        components=tuple(from_artifact.get(name) or backend_only[name] for name in order)
    )


UI_KIT = _build_ui_kit()

COMPONENT_NAMES: tuple[str, ...] = UI_KIT.names
LLM_COMPONENT_NAMES: tuple[str, ...] = UI_KIT.llm_names
CONTAINER_NAMES: tuple[str, ...] = UI_KIT.container_names

