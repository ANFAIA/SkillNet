"""The SkillNet UI Kit — the frozen catalogue of §5.3, validator side.

This module is the source of truth for **validation**: the component list, the exact
prop names, the value types, the closed enums and the *positional* order the OpenUI
dialect uses. ``src/render/spec.py`` enforces all of it, and the OpenUI parser cannot:
``compileSchema()`` keeps only ``{name, required, defaultValue}``, so their parser checks
arity and presence and nothing else.

Since 2026-07-26 the prompt itself is generated by ``library.prompt()`` from the
frontend kit (``apps/skillnet-web/src/components/courses/kit/``), and since this rewrite
this module no longer *retypes* that catalogue by hand either: for every component the
frontend advertises to the model, the name/props/description come straight from
``openui_catalog.json`` (the same artefact ``src/render/prompt.py`` reads), loaded once at
import time by :func:`_load_llm_components`. There is exactly one authored catalogue —
the frontend kit — and this module derives its half of the validator from it, so a prop
renamed, reordered or retyped there arrives here automatically the next time the artefact
is regenerated; ``tests/test_render_prompt_artifact.py`` still exists, but only to catch a
stale or hand-tampered artefact, not to compare two independent declarations.

The artefact cannot carry everything a ``ComponentSpec`` needs, because it is written for
the model prompt, not for Python: it says nothing about which block is a *container*,
which function it competes for (``ContentFunction``/``FunctionFit``), or which components
exist for the backend only and never reach the frontend prompt catalogue at all
(``Markdown`` — server-authored fallback; ``DidactActivity`` — legacy, playback-only;
``PodcastPlayer``/``InfographicImage``/``SourceImage`` — broker-scoped, injected
per-node). That metadata is genuinely backend business, so it stays declared here, in
:data:`_BACKEND_METADATA`
(keyed by name, for the JSON-derived components) and in :data:`_BACKEND_ONLY_COMPONENTS`
(full hand-written specs, for the five components the artefact does not describe at all).

Two closed lists are imported instead of retyped, so they cannot drift either:
``ExerciseType`` (the six ``item_type`` values, §5.3) and ``BLOOM_LEVELS`` (the six
values the ``node_attempts.bloom_level`` CHECK accepts, §3.4).
"""

